    /// In-memory database with the schema in place.
    ///
    /// `auto_migrate` only upgrades an existing schema, so the tables have to be
    /// created from the same DDL the server uses.
    fn test_conn() -> Connection {
        let conn = Connection::open_in_memory().unwrap();
        conn.pragma_update(None, "foreign_keys", 1).unwrap();
        conn.execute(crate::db::cidr::CREATE_TABLE_SQL, []).unwrap();
        conn.execute(crate::db::peer::CREATE_TABLE_SQL, []).unwrap();
        conn.execute(crate::db::association::CREATE_TABLE_SQL, [])
            .unwrap();
        conn
    }

    /// The invitation must carry the private key in a form `innernet install`
    /// accepts, and the server must not have stored it.
    #[test]
    fn invitation_contains_a_usable_config_and_the_db_stores_only_the_public_key() {
        let conn = test_conn();
        let cidr = DatabaseCidr::create(
            &conn,
            innernet_shared::CidrContents {
                name: "humans".parse().unwrap(),
                cidr: "10.60.1.0/24".parse().unwrap(),
                parent: None,
            },
        )
        .unwrap();

        // Seed the server peer (id 1), which the invitation names as its server.
        let server_peer = DatabasePeer::create(
            &conn,
            PeerContents {
                name: "innernet-server".parse().unwrap(),
                ip: "10.60.1.1".parse().unwrap(),
                cidr_id: cidr.id,
                public_key: wireguard_control::KeyPair::generate().public.to_base64(),
                endpoint: Some("104.129.59.241:51820".parse().unwrap()),
                persistent_keepalive_interval: None,
                is_admin: true,
                is_disabled: false,
                is_redeemed: true,
                invite_expires: None,
                candidates: vec![],
                allowed_subnets: vec![],
            },
        )
        .unwrap();
        assert_eq!(server_peer.id, 1);

        let keypair = wireguard_control::KeyPair::generate();
        let interface_info = InterfaceInfo::new(
            &"wg0".parse().unwrap(),
            &keypair,
            "10.60.1.5/24".parse().unwrap(),
        );
        let server_info = ServerInfo::new(server_peer.deref(), "10.60.1.1:51820".parse().unwrap());
        let invitation = PeerInvitation::new(interface_info, server_info);
        let toml = invitation.to_toml().unwrap();

        // Parses back as a config, so `innernet install` would accept it. The
        // preamble is comments, so TOML parsing ignores it.
        let parsed: innernet_shared::interface_config::InterfaceConfig =
            toml::from_str(&toml).unwrap();
        assert_eq!(parsed.interface.network_name, "wg0");
        assert_eq!(parsed.interface.private_key, keypair.private.to_base64());
        assert_eq!(parsed.interface.address.to_string(), "10.60.1.5/24");
        assert_eq!(
            parsed.server.external_endpoint.to_string(),
            "104.129.59.241:51820"
        );

        // The database holds only the public half: the private key exists
        // solely inside the returned string.
        let peers = DatabasePeer::list(&conn).unwrap();
        for p in &peers {
            assert!(
                !p.public_key.contains(&keypair.private.to_base64()),
                "the private key must never be persisted"
            );
        }
    }

